#!/usr/bin/env node
/**
 * 把纯逻辑 core.cjs 内联进浏览器端 client.js，并把资源摘要写进 ASSET_REV。
 * 发布物仍是一个自包含的 ESM 文件，DSH 客户端加载器不需要额外请求。
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, sep } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assetsDir = join(root, "assets");

async function walk(dir) {
	const entries = await readdir(dir, { withFileTypes: true });
	const files = [];
	for (const entry of entries) {
		const full = join(dir, entry.name);
		if (entry.isDirectory()) files.push(...await walk(full));
		else if (entry.isFile()) files.push(full);
	}
	return files;
}

/**
 * sheet/语音/头像任一变化都会让客户端请求新 URL，避免旧尺寸图集被缓存。
 *
 * 摘要必须与平台无关：相对路径统一用 "/" 分隔、按该字符串排序，
 * 否则 Windows（"\\"）与 Linux（"/"）算出的 rev 不同，CI 的
 * 「Bundle is committed」校验会误报。
 */
export async function assetRevision() {
	const entries = (await walk(assetsDir)).map((file) => ({
		rel: relative(assetsDir, file).split(sep).join("/"),
		file,
	}));
	entries.sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0));
	const hash = createHash("sha256");
	for (const entry of entries) {
		hash.update(entry.rel);
		hash.update(await readFile(entry.file));
	}
	return hash.digest("hex").slice(0, 12);
}

export async function renderClient() {
	const core = await readFile(join(root, "src/core.cjs"), "utf8");
	let client = await readFile(join(root, "src/client.js"), "utf8");
	if (!client.includes("__KONP_ASSET_REV__")) throw new Error("src/client.js 缺少 __KONP_ASSET_REV__ 占位符");
	client = client.replaceAll("__KONP_ASSET_REV__", await assetRevision());
	return `/* dsh-k-on-pet — generated by scripts/build-client.mjs; edit src/ instead. */\n` + core + "\n" + client;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const rev = await assetRevision();
	await writeFile(join(root, "lib/client.js"), await renderClient());
	console.log(`built lib/client.js (assets ${rev})`);
}
