#!/usr/bin/env node
/**
 * 把纯逻辑 core.cjs 内联进浏览器端 client.js。
 * 发布物仍是一个自包含的 ESM 文件，DSH 客户端加载器不需要额外请求。
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const core = await readFile(join(root, "src/core.cjs"), "utf8");
const client = await readFile(join(root, "src/client.js"), "utf8");
const banner = `/* dsh-k-on-pet — generated by scripts/build-client.mjs; edit src/ instead. */\n`;

await writeFile(join(root, "lib/client.js"), banner + core + "\n" + client);
console.log("built lib/client.js");
